import { useEffect, useState } from "react";
import { Button, Flex, Form, Input, Space, Tooltip } from "antd";
import { PlusOutlined } from "@ant-design/icons";
import {
  createDatasetSubjectApi,
  createSubjectApi,
  getDatasetSubjectBySubjectApi,
  updateDatasetSubjectApi,
  updateSubjectApi,
} from "@/api/data";
import type { DatasetItem, DatasetSubjectItem, SubjectItem } from "@/api/data";
import { invoke } from "@/core/ui-system/invokeV2";
import { useGlobalMessage } from "@/hooks/useGlobalMessage";

/**
 * Subject as edited here. `dataset_id` / `dataset_name` only exist on the
 * project read model (SubjectWithDatasetInfo).
 */
export type SubjectFormSource = SubjectItem & {
  dataset_id?: string;
  dataset_name?: string;
};

export interface EditSubjectPageProps {
  /** When provided the form updates the subject, otherwise it creates a new one. */
  subject?: SubjectFormSource;
  /**
   * Optional pre-selected dataset. A dataset binds to the top-level Subject
   * (go_dataset_subject), so this form writes that binding alongside the subject
   * itself — it is the only place `dataset_id` lives.
   */
  dataset?: Pick<DatasetItem, "id" | "dataset_name">;
  onOk?: (result: SubjectItem) => void;
  onCancel?: () => void;
  close?: () => void;
}

const trimOrUndefined = (value?: string) => {
  const trimmed = value?.trim();
  return trimmed ? trimmed : undefined;
};

/** Picker label: prefer the dataset display name, fall back to its id. */
const datasetLabel = (dataset?: Pick<DatasetItem, "id" | "dataset_name">) =>
  dataset ? dataset.dataset_name || dataset.id : "";

/**
 * Subject (donor / individual) create & edit form.
 *
 * `subject_name` is both the business identifier (e.g. "mouse-001") and the
 * human-readable display name (Chinese or with spaces, e.g. "小鼠 001"); it is
 * required and only has to be unique within a dataset. The PK is always
 * generated by the backend.
 *
 * A Subject joins a project through its dataset binding (go_dataset_subject),
 * so the dataset is picked here too and written as a DatasetSubject record —
 * that is the only place `dataset_id` lives in the
 * Subject -> Sample -> Assay -> File branch.
 */
const EditSubjectPage = ({ subject, dataset, onOk, onCancel, close }: EditSubjectPageProps) => {
  const [form] = Form.useForm();
  const [loading, setLoading] = useState(false);
  const [selectedDataset, setSelectedDataset] = useState<
    Pick<DatasetItem, "id" | "dataset_name"> | undefined
  >();
  // Binding of the edited subject (go_dataset_subject); undefined until loaded.
  const [binding, setBinding] = useState<DatasetSubjectItem>();
  const message = useGlobalMessage();

  const isEdit = Boolean(subject?.id);

  useEffect(() => {
    if (isEdit && subject) {
      form.setFieldsValue({
        subject_name: subject.subject_name ?? "",
        species: subject.species ?? "",
        strain: subject.strain ?? "",
        sex: subject.sex ?? "",
        age: subject.age ?? "",
        metadata: subject.metadata ?? "",
        description: subject.description ?? "",
      });
      setSelectedDataset(
        subject.dataset_id
          ? { id: subject.dataset_id, dataset_name: subject.dataset_name ?? "" }
          : undefined
      );

      // The subject read model only carries the dataset ids, so load the binding
      // itself to know whether to update it (or create it when it is missing).
      let cancelled = false;
      const loadBinding = async () => {
        const response = await getDatasetSubjectBySubjectApi(subject.id).catch(() => undefined);
        if (!cancelled && response?.data) {
          setBinding(response.data);
        }
      };

      void loadBinding();
      return () => {
        cancelled = true;
      };
    }

    form.resetFields();
    setSelectedDataset(dataset ? { id: dataset.id, dataset_name: dataset.dataset_name } : undefined);
    setBinding(undefined);
  }, [subject, dataset, isEdit, form]);

  const handleSelectDataset = async () => {
    try {
      const picked = await invoke.datasetProjectPage.openDrawerAsync(
        {},
        { width: 760, title: "Select Dataset" }
      );
      if (picked?.id) {
        setSelectedDataset(picked as DatasetItem);
      }
    } catch {
      // user cancelled
    }
  };

  const handleCreateDataset = async () => {
    try {
      const created = await invoke.editDatasetPage.openDrawerAsync(
        {},
        { width: 480, title: "New Dataset" }
      );
      if (created?.id) {
        setSelectedDataset(created as DatasetItem);
      }
    } catch {
      // user cancelled
    }
  };

  const handleSubmit = async () => {
    if (!isEdit && !selectedDataset?.id) {
      message.error("Please select a dataset");
      return;
    }

    try {
      const values = await form.validateFields();
      setLoading(true);

      const payload = {
        subject_name: String(values.subject_name ?? "").trim(),
        species: trimOrUndefined(values.species),
        strain: trimOrUndefined(values.strain),
        sex: trimOrUndefined(values.sex),
        age: trimOrUndefined(values.age),
        metadata: trimOrUndefined(values.metadata),
        description: trimOrUndefined(values.description),
      };

      const result = isEdit
        ? await updateSubjectApi({ id: subject!.id, ...payload })
        : await createSubjectApi(payload);

      // A subject joins a project through go_dataset_subject, so the binding is
      // written here too — otherwise the subject never shows up in the project.
      if (selectedDataset?.id) {
        const subjectId = String(result.data.id);
        if (binding?.id) {
          if (binding.dataset_id !== selectedDataset.id) {
            await updateDatasetSubjectApi({
              id: binding.id,
              dataset_id: selectedDataset.id,
              subject_id: subjectId,
            });
          }
        } else if (subject?.dataset_id !== selectedDataset.id) {
          await createDatasetSubjectApi({
            dataset_id: selectedDataset.id,
            subject_id: subjectId,
          });
        }
      }

      message.success(isEdit ? "Subject updated successfully" : "Subject created successfully");
      onOk?.(result.data);
    } catch (error: any) {
      if (error?.errorFields) return; // validation error, keep the drawer open
      message.error(isEdit ? "Failed to update subject" : "Failed to create subject");
    } finally {
      setLoading(false);
    }
  };

  const handleCancel = () => {
    if (onCancel) {
      onCancel();
      return;
    }
    close?.();
  };

  return (
    <Form form={form} layout="vertical">
      <Form.Item
        label="Dataset"
        required={!isEdit}
        tooltip="A subject joins a project through its dataset (DatasetSubject). Picking one here writes that binding; without it the subject does not show up in the project."
      >
        <Space.Compact style={{ width: "100%" }}>
          <Tooltip title={datasetLabel(selectedDataset)}>
            <Input
              readOnly
              value={datasetLabel(selectedDataset)}
              placeholder="Click to select a dataset"
              onClick={handleSelectDataset}
              style={{ cursor: "pointer", flex: 1 }}
            />
          </Tooltip>
          <Button onClick={handleSelectDataset}>
            {selectedDataset ? "Change" : "Select"}
          </Button>
          <Button type="primary" ghost icon={<PlusOutlined />} onClick={handleCreateDataset}>
            New
          </Button>
        </Space.Compact>
      </Form.Item>

      <Form.Item
        name="subject_name"
        label="Subject Name"
        tooltip="Business identifier / display name (e.g. mouse-001 or 小鼠 001); required and unique within a dataset, may repeat in another dataset"
        rules={[{ required: true, message: "Please input the subject name" }]}
      >
        <Input placeholder="e.g. mouse-001" />
      </Form.Item>

      <Form.Item name="species" label="Species">
        <Input placeholder="e.g. Mus musculus" />
      </Form.Item>

      <Form.Item name="strain" label="Strain">
        <Input placeholder="e.g. C57BL/6J" />
      </Form.Item>

      <Flex gap="small">
        <Form.Item name="sex" label="Sex" style={{ flex: 1 }}>
          <Input placeholder="e.g. male / female" />
        </Form.Item>
        <Form.Item name="age" label="Age" style={{ flex: 1 }}>
          <Input placeholder="e.g. 8 weeks" />
        </Form.Item>
      </Flex>

      <Form.Item name="metadata" label="Metadata">
        <Input.TextArea rows={3} placeholder="Free-form metadata" />
      </Form.Item>

      <Form.Item name="description" label="Description">
        <Input.TextArea rows={2} placeholder="Description" />
      </Form.Item>

      <Flex justify="end" gap="small">
        <Button onClick={handleCancel}>Cancel</Button>
        <Button type="primary" loading={loading} onClick={handleSubmit}>
          {isEdit ? "Save" : "Create"}
        </Button>
      </Flex>
    </Form>
  );
};

export default EditSubjectPage;
